def classify(report_nm: str) -> Rule:
    name = report_nm.replace(" ", "")
    for rule in RULES:
        if any(w.replace(" ", "") in name for w in rule.words):
            return _with_detail(rule)
    return DEFAULT


def _with_detail(rule: Rule) -> Rule:
    detail = DETAILS.get(rule.category)
    return replace(rule, why=detail[0], checks=detail[1]) if detail else rule


def is_correction(report_nm: str) -> bool:
    """[기재정정]·[첨부정정]처럼 이미 낸 공시를 고친 것."""
    return "정정" in report_nm[:8]
