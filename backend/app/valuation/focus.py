LOSS_TITLE = "적자라서 PER 대신 PBR을 봐요"
LOSS_REASON = (
    "최근 1년 적자라 PER을 계산할 수 없어요. 이럴 땐 가진 자산에 비해 주가가 어떤지(PBR)와 실적이 나아지고 있는지를 봐요."
)

_BY_NAME = {name: g for g in GUIDES for name in g.names}


def decide(industry_name: str | None, eps: float | None) -> Focus:
    guide = _BY_NAME.get((industry_name or "").strip(), DEFAULT)
    # 적자면 PER을 쓸 수 없다. 함께 볼 것·주의는 업종 것을 그대로 두고 제목과 이유만 바꾼다.
    # (바이오처럼 원래 둘 다 안 맞는 업종은 그 설명을 그대로 쓴다)
    if eps is not None and eps <= 0 and guide.focus != "none":
        return replace(guide, focus="pbr", title=LOSS_TITLE, reason=f"{LOSS_REASON} 원래 이 업종은: {guide.reason}")
    return guide
